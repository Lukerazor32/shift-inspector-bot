const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

function buttonsHtml(rows, cls, hl) {
  if (!rows || !rows.length) return "";
  return (
    `<div class="${cls}">` +
    rows
      .map((row) => `<div class="row">${row.map((b) => `<button tabindex="-1" class="${b === hl ? "is-hl" : ""}">${esc(b)}</button>`).join("")}</div>`)
      .join("") +
    "</div>"
  );
}

function msgHtml(m, hl) {
  switch (m.t) {
    case "sys":
      return `<div class="sys">${esc(m.text)}</div>`;
    case "toast":
      return `<div class="toast">${icon("check-circle")}${esc(m.text)}</div>`;
    case "me":
      return `<div class="msg out">${m.html}<span class="time">${m.time || "08:05"}</span></div>`;
    case "bot":
      return `<div class="msg">${m.html}<span class="time">${m.time || "08:05"}</span></div>` + buttonsHtml(m.buttons, "ikb", hl);
    case "file":
      return (
        `<div class="msg${m.out ? " out" : ""}"><div class="file"><span class="fi${m.out ? " blue" : ""}">${icon("sheet")}</span><div><b>${esc(m.name)}</b><small>XLSX · 24 КБ</small></div></div>` +
        (m.caption ? esc(m.caption) : "") +
        `<span class="time">08:06</span></div>`
      );
    case "photo": {
      const who = m.who ? `<div class="who" style="padding:2px 6px 4px">${esc(m.who)}</div>` : "";
      return (
        `<div class="msg photo${m.out ? " out" : ""}"${m.bot ? ' style="max-width:88%"' : ""}>${who}<div class="pic ${m.pic || "p1"}"><svg viewBox="0 0 100 90"><use href="#i-guard"/></svg></div>` +
        `<div class="cap">${m.html}<span class="time">${m.time || "08:47"}</span></div></div>` +
        buttonsHtml(m.buttons, "ikb", hl)
      );
    }
    default:
      return "";
  }
}

function screenHtml(s) {
  const chat = CHATS[s.chat] || CHATS.bot;
  const body = s.msgs.map((m) => msgHtml(m, s.hl)).join("");
  let bottom = "";
  if (s.start) {
    bottom = `<div class="start-wrap"><button tabindex="-1" class="start-btn ${s.hl === "ЗАПУСТИТЬ" ? "is-hl" : ""}">ЗАПУСТИТЬ</button></div>`;
  } else if (s.kb) {
    bottom = `<div class="tg-input">${icon("paperclip")}<span class="pill">Сообщение</span>${icon("mic")}</div>` + buttonsHtml(s.kb, "rkb", s.hl);
  } else {
    bottom = `<div class="tg-input">${icon("paperclip")}<span class="pill">Сообщение</span>${icon("mic")}</div>`;
  }
  return `
    <div class="phone"><div class="screen">
      <div class="tg-head">
        <span class="tg-back">‹</span>
        <span class="tg-ava">${chat.ava}</span>
        <div><div class="tg-title">${esc(chat.title)}</div><div class="tg-sub">${esc(chat.sub)}</div></div>
      </div>
      <div class="tg-body">${body}</div>
      ${bottom}
    </div></div>`;
}

