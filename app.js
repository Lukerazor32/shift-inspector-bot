panelEl.addEventListener("click", (e) => {
  const role = ROLES.find((r) => r.id === state.role);
  const guide = role.guides[state.guide];
  const g = e.target.closest("[data-guide]");
  if (g) {
    state.guide = +g.dataset.guide;
    setStep(0);
    return;
  }
  const s = e.target.closest("[data-step]");
  if (s) {
    setStep(+s.dataset.step);
    focusPhone();
    return;
  }
  const n = e.target.closest("[data-nav]");
  if (n) {
    const next = state.step + +n.dataset.nav;
    if (next < 0) return;
    if (next >= guide.steps.length) {
      state.guide = (state.guide + 1) % role.guides.length;
      setStep(0);
      panelEl.scrollIntoView({ behavior: "smooth", block: "start" });
      return;
    }
    setStep(next);
    focusPhone();
  }
});

